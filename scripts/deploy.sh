#!/usr/bin/env bash
# One-command deploy: build the React frontend, deploy the bundle (silver
# pipelines + app), then grant the catalog/schema USE privileges that
# `uc_securable` resources can't declare.
#
# Usage:
#   ./scripts/deploy.sh [--target dev|prod] [-- bundle-vars...]
#
# Examples:
#   ./scripts/deploy.sh
#   ./scripts/deploy.sh --target prod
#   ./scripts/deploy.sh --target dev --var "warehouse_id=abc123"
set -euo pipefail

cd "$(dirname "$0")/.."

TARGET="dev"
EXTRA_ARGS=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --target)
      TARGET="$2"; shift 2 ;;
    *)
      EXTRA_ARGS+=("$1"); shift ;;
  esac
done

echo "==> Building frontend"
(cd app/frontend && npm install --silent && npm run build)

# Render app/app.yaml from bundle variables. Databricks Apps reads env vars
# from this file at runtime — the bundle resource's config block is ignored
# by the Direct deploy engine, so we have to put env on disk.
echo "==> Reading bundle variables"
SUMMARY=$(databricks bundle summary --target "$TARGET" --output json ${EXTRA_ARGS[@]+"${EXTRA_ARGS[@]}"})
read_var() {
  echo "$SUMMARY" | python3 -c "
import json, sys
v = json.load(sys.stdin)['variables']['$1']
print(v.get('value') or v.get('default') or '')
"
}
WAREHOUSE_ID=$(read_var warehouse_id)
GENIE_SPACE_ID=$(read_var genie_space_id)
CATALOG=$(read_var dest_catalog)
SCHEMA=$(read_var app_otel_schema)

if [[ -z "$WAREHOUSE_ID" || -z "$GENIE_SPACE_ID" ]]; then
  echo "ERROR: warehouse_id and genie_space_id are required." >&2
  echo "  Set them via --var or in a databricks.yml override file." >&2
  exit 1
fi

echo "==> Rendering app/app.yaml (warehouse=$WAREHOUSE_ID schema=$CATALOG.$SCHEMA)"
cat > app/app.yaml <<EOF
# Auto-generated by scripts/deploy.sh from bundle variables. Do not edit.
command: ['uvicorn', 'app:app', '--host', '0.0.0.0', '--port', '8000']

env:
  - name: 'DATABRICKS_WAREHOUSE_ID'
    value: '$WAREHOUSE_ID'
  - name: 'GENIE_SPACE_ID'
    value: '$GENIE_SPACE_ID'
  - name: 'OTEL_CATALOG'
    value: '$CATALOG'
  - name: 'OTEL_SCHEMA'
    value: '$SCHEMA'
EOF

echo "==> Deploying bundle to '$TARGET'"
databricks bundle deploy --target "$TARGET" ${EXTRA_ARGS[@]+"${EXTRA_ARGS[@]}"}

echo "==> Granting USE_CATALOG / USE_SCHEMA to the app's service principal"
APP_NAME=$(databricks bundle summary --target "$TARGET" --output json 2>/dev/null \
  | python3 -c 'import json,sys
d=json.load(sys.stdin)
apps=d.get("resources",{}).get("apps",{}) or {}
print(next(iter(apps.values()))["name"])')

CATALOG=$(databricks bundle summary --target "$TARGET" --output json 2>/dev/null \
  | python3 -c 'import json,sys,os
d=json.load(sys.stdin)
print(d["variables"]["dest_catalog"]["value"])')

SCHEMA=$(databricks bundle summary --target "$TARGET" --output json 2>/dev/null \
  | python3 -c 'import json,sys
d=json.load(sys.stdin)
print(d["variables"]["app_otel_schema"]["value"])')

WAREHOUSE_ID=$(databricks bundle summary --target "$TARGET" --output json 2>/dev/null \
  | python3 -c 'import json,sys
d=json.load(sys.stdin)
print(d["variables"]["warehouse_id"]["value"])')

APP_NAME="$APP_NAME" \
CATALOG="$CATALOG" \
SCHEMA="$SCHEMA" \
WAREHOUSE_ID="$WAREHOUSE_ID" \
  scripts/grant-app-permissions.sh

APP_URL=$(databricks apps get "$APP_NAME" --output json | python3 -c '
import json,sys
print(json.load(sys.stdin).get("url",""))')

echo
echo "==> Done. App URL:"
echo "    $APP_URL"
